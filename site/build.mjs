index = index.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")), grid);
/* the "All (N)" filter chip lives outside the markers — keep its count honest */
const chipRe = /(data-filter="all"[^>]*>)All \(\d+\)(<)/;
if (!chipRe.test(index)) throw new Error('could not find the All (N) filter chip in index.html');
index = index.replace(chipRe, `$1All (${KFOOD_PRODUCTS.length})$2`);

writeFileSync("index.html", index);
