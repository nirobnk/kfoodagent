/* ============================================================
   K FOOD static build
   - injects the product grid into index.html (between markers)
   - generates products/<handle>.html (one static page per product)
   - regenerates sitemap.xml
   Run after editing products-data.js:  node build.mjs
   ============================================================ */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { KFOOD_PRODUCTS } = require("./products-data.js");

